/**
 * Write the Word document the file preview demo opens.
 *
 * Generated rather than copied, like `make-sample-pdf.ts`, so nothing here carries
 * someone else's licence — and written part by part, so it shows what the renderer
 * is being asked to draw: styles, headings, both kinds of list, a shaded table, an
 * embedded picture, a hyperlink, a footer, and a page break.
 *
 * The zip is stored, not deflated: a few kilobytes either way, and it keeps the
 * script free of dependencies.
 *
 * Usage: bun run scripts/make-sample-docx.ts
 */
import { writeFileSync } from 'node:fs';
