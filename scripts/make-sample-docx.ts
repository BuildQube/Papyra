const PKG_REL = 'http://schemas.openxmlformats.org/package/2006/relationships';

const xml = (body: string) =>
  `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n${body}`;

/** A run of text, with optional run properties. */
const run = (text: string, props = '') =>
  `<w:r>${props ? `<w:rPr>${props}</w:rPr>` : ''}<w:t xml:space="preserve">${text}</w:t></w:r>`;

const para = (content: string, props = '') =>
  `<w:p>${props ? `<w:pPr>${props}</w:pPr>` : ''}${content}</w:p>`;

const styled = (style: string, text: string) =>
  para(run(text), `<w:pStyle w:val="${style}"/>`);

const listItem = (numId: number, text: string) =>
  para(
    run(text),
    `<w:pStyle w:val="ListParagraph"/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="${numId}"/></w:numPr>`,
  );

const cell = (text: string, header = false, align = 'left') =>
  `<w:tc><w:tcPr><w:tcW w:w="2400" w:type="dxa"/>${
    header ? '<w:shd w:val="clear" w:color="auto" w:fill="1F2937"/>' : ''
  }</w:tcPr>${para(
    run(text, header ? '<w:b/><w:color w:val="FFFFFF"/>' : ''),
    `<w:jc w:val="${align}"/>`,
  )}</w:tc>`;

